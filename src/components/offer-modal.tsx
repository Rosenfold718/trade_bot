export default function OfferModal({ open, onClose, onAccept }: OfferModalProps) {
  const [expandedSections, setExpandedSections] = useState<Set<number>>(new Set([2, 7])); // Expand risk sections by default
  const [scrolledToBottom, setScrolledToBottom] = useState(false);

  const toggleSection = (idx: number) => {
    setExpandedSections(prev => {
      const next = new Set(prev);
      if (next.has(idx)) next.delete(idx);
      else next.add(idx);
      return next;
    });
  };

  const handleScroll = (e: React.UIEvent<HTMLDivElement>) => {
    const el = e.currentTarget;
    const isBottom = Math.abs(el.scrollHeight - el.scrollTop - el.clientHeight) < 20;
    setScrolledToBottom(isBottom);
  };

  if (!open) return null;

  return (
    <div className="fixed inset-0 z-[350] bg-[#0a0a0f]/98 backdrop-blur-sm flex items-center justify-center p-4">
      <Card className="w-full max-w-2xl max-h-[90vh] flex flex-col bg-[#12121e]/98 border-white/[0.08] rounded-2xl shadow-2xl">
        <CardContent className="p-5 flex-1 min-h-0 flex flex-col overflow-hidden">
          {/* Header */}
          <div className="flex items-center justify-between mb-4 shrink-0">
            <div className="flex items-center gap-3">
              <div className="w-10 h-10 rounded-xl bg-amber-500/10 border border-amber-500/20 flex items-center justify-center">
                <FileText className="h-5 w-5 text-amber-400" />
              </div>
              <div>
                <h2 className="text-base font-bold text-white">Пользовательское соглашение</h2>
                <p className="text-[10px] text-white/30 font-mono">Оферта · Необходимо прочитать полностью</p>
              </div>
            </div>
            <button onClick={onClose} className="p-2 rounded-lg hover:bg-white/[0.06] text-white/30 hover:text-white/50 transition-colors">
              <X className="w-4 h-4" />
            </button>
          </div>

          {/* Scrollable content */}
          <div
            className="flex-1 min-h-0 overflow-y-auto space-y-2 pr-1 custom-scroll"
            onScroll={handleScroll}
          >
            {OFFER_SECTIONS.map((section, idx) => (
              <div key={idx} className="border border-white/[0.04] rounded-xl overflow-hidden">
                <button
                  onClick={() => toggleSection(idx)}
                  className="w-full flex items-center justify-between px-4 py-2.5 hover:bg-white/[0.02] transition-colors"
                >
                  <span className="text-xs font-medium text-white/60">{section.title}</span>
                  {expandedSections.has(idx) ? (
                    <ChevronUp className="w-3.5 h-3.5 text-white/20" />
                  ) : (
                    <ChevronDown className="w-3.5 h-3.5 text-white/20" />
                  )}
                </button>
                {expandedSections.has(idx) && (
                  <div className="px-4 pb-3">
                    <p className="text-[11px] text-white/40 leading-relaxed whitespace-pre-line">{section.content}</p>
                  </div>
                )}
              </div>
            ))}
          </div>

          {/* Scroll indicator */}
          {!scrolledToBottom && (
            <div className="shrink-0 py-2 text-center">
              <p className="text-[10px] text-amber-400/60 animate-pulse">
                ↓ Прокрутите до конца для продолжения
              </p>
            </div>
          )}

          {/* Footer */}
          <div className="pt-4 mt-3 border-t border-white/[0.04] shrink-0 space-y-3">
            <Button
              onClick={onAccept}
              disabled={!scrolledToBottom}
              className="w-full h-10 bg-emerald-600 hover:bg-emerald-500 text-white text-sm font-semibold rounded-lg transition-all disabled:opacity-30 disabled:cursor-not-allowed"
            >
              Принимаю условия
            </Button>
          </div>
        </CardContent>
      </Card>
    </div>
  );
}
